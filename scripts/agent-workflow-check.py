"""``agent-workflow.yaml`` loader.

Reads a YAML config, validates against the JSON Schema at
``core/schema/agent-workflow.schema.json``, and exposes a typed view.

Slice Step 2 covers only the ``workRecord`` block; further fields land
incrementally as their owning backlog items are picked up.
"""




# ---------------------------------------------------------------------------
# Public types
# ---------------------------------------------------------------------------


class ConfigError(ValueError):
    """Raised when the config file is missing, unreadable, or invalid.

    Carries a short, human-readable reason. Callers (the checker, the
    skill driver, bootstrap) translate it into named-predicate failures
    in their own surfaces.
    """


@dataclass(frozen=True)
class LocalBackendConfig:
    """Options for the local Markdown Work Record backend."""

    task_path: str
    """Repo-relative path template, e.g. ``.agent-workflow/tasks/{slug}.md``."""


@dataclass(frozen=True)
class WorkRecordConfig:
    """Work Record backend selection plus backend-specific options."""

    backend: str
    """``local`` or ``jira``."""

    local: LocalBackendConfig | None
    """Populated when ``backend == 'local'``; ``None`` otherwise."""

    required_for_branch_changes: bool = True
    """When True (default), the CI checker emits a blocking
    ``workrecord.required_for_branch_changes`` predicate when a PR
    touched code paths but resolved no Work Record at the branch slug.
    Set to ``False`` to allow pure-housekeeping PRs (vendored-script
    bumps, formatter-only passes) through without a Work Record.
    Schema-default is ``True`` so the harness's "every engineering
    task has a Work Record" contract is on by default."""

    # Jira options are intentionally absent here; W18 introduces them
    # alongside the Jira backend implementation. The schema reserves the
    # shape so config files written today are forward-compatible.


@dataclass(frozen=True)
class RedlineConfig:
    """agent-redline integration options.

    Slice B introduces both fields; they default per the docstrings
    when omitted from the YAML so existing configs (which pre-date this
    slice) keep working unchanged.
    """

    required: bool
    """``True`` when ``redline: required`` (the default). ``False``
    when ``redline: optional`` (an explicit opt-out — the CI checker
    treats a missing verdict as advisory instead of blocking)."""

    verdict_path: str
    """Path the checker reads to find redline's verdict JSON. Default:
    ``build/redline-verdict.json``."""


@dataclass(frozen=True)
class Config:
    """Typed view of the per-repo ``agent-workflow.yaml``.

    Only fields the current slice consumes are surfaced. The raw mapping
    is kept on :attr:`raw` for forward compatibility — callers that want
    to peek at an unsupported field can read it without waiting for the
    loader to grow a typed accessor.
    """

    version: int
    project_name: str
    work_record: WorkRecordConfig
    redline: RedlineConfig
    raw: dict[str, Any]


# ---------------------------------------------------------------------------
# Schema location
# ---------------------------------------------------------------------------



def _schema() -> dict[str, Any]:
    """Return the inlined config schema."""
    return _INLINED_SCHEMA


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------


def _load_yaml(path: Path) -> dict[str, Any]:
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError as exc:
        raise ConfigError(f"config file not found: {path}") from exc
    except OSError as exc:
        raise ConfigError(f"could not read config file {path}: {exc}") from exc

    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise ConfigError(f"config file {path} is not valid YAML: {exc}") from exc

    if data is None:
        raise ConfigError(f"config file {path} is empty")
    if not isinstance(data, dict):
        raise ConfigError(
            f"config file {path} must be a YAML mapping at the top level "
            f"(got {type(data).__name__})"
        )
    return data


def _validate(data: dict[str, Any]) -> None:
    """Raise :exc:`ConfigError` if ``data`` does not match the schema.

    Uses ``jsonschema``'s draft-2020-12 validator; reports the first
    error with its JSON Pointer-style path so the failing field is
    obvious without a debugger.
    """
    validator = jsonschema.Draft202012Validator(_schema())
    errors = sorted(validator.iter_errors(data), key=lambda e: list(e.absolute_path))
    if not errors:
        return

    first = errors[0]
    path = "/".join(str(p) for p in first.absolute_path) or "(root)"
    raise ConfigError(f"config invalid at {path}: {first.message}")


def _to_config(data: dict[str, Any]) -> Config:
    """Pull validated data into the typed Config view.

    Validation has already enforced presence and types of the fields we
    read here, so no defensive `get()`-with-default — a missing field
    would be a schema bug, not a runtime case to handle.

    Optional top-level fields with their own defaults (``redline``,
    ``redlineVerdictPath``) DO use ``.get()`` with explicit defaults —
    the schema permits their absence and the defaults are documented as
    part of the loader contract.
    """
    work_record = data["workRecord"]
    backend = work_record["backend"]

    local: LocalBackendConfig | None
    if backend == "local":
        local_block = work_record["local"]
        local = LocalBackendConfig(task_path=local_block["taskPath"])
    else:
        # backend == "jira" — full options land with W18. Surface as
        # None so callers that try to use it before then see an
        # obvious failure rather than a silent half-config.
        local = None

    redline = RedlineConfig(
        required=data.get("redline", "required") == "required",
        verdict_path=data.get("redlineVerdictPath", "build/redline-verdict.json"),
    )

    return Config(
        version=data["version"],
        project_name=data["project"]["name"],
        work_record=WorkRecordConfig(
            backend=backend,
            local=local,
            required_for_branch_changes=bool(
                work_record.get("requiredForBranchChanges", True)
            ),
        ),
        redline=redline,
        raw=data,
    )


def load(path: Path | str) -> Config:
    """Read, validate, and return the typed config at ``path``.

    Raises :exc:`ConfigError` on any failure: missing file, bad YAML,
    schema violation. The error message names the offending field where
    possible.
    """
    data = _load_yaml(Path(path))
    _validate(data)
    return _to_config(data)

# ----- core/checker/verdict.py -----

"""Checker verdict types.

Kept small and stable — the GitHub Action serialises the JSON shape
directly into the sticky PR comment, so the structure is part of the
harness's public surface even though the dataclasses are internal.

Two levels:

- :class:`RecordVerdict` — one Work Record's verdict. Carries the
  slug, the per-record status / exit_code, and the ordered list of
  :class:`PredicateResult` for that record. Per-record status uses the
  same rule the single-record verdict used before slice 0: any blocking
  failed → ``blocking``; else any advisory failed → ``advisory``;
  else ``clean``.

- :class:`Verdict` — the overall verdict for a PR. Carries the rolled-
  up status / exit_code across all records, plus the per-record list
  in order. Overall aggregation uses the same rule across records.

A single-record run wraps its one record in ``records[0]``; multi-record
runs nest each.
"""




@dataclass(frozen=True)
class PredicateResult:
    """Result of one predicate evaluation.

    Names are dotted (``workrecord.exists``) so they're greppable in
    logs and stable across releases — tests pin them as goldens. The
    detail is a short human sentence; we deliberately don't try to be
    structured here because the predicate name is the structured part.
    """

    name: str
    passed: bool
    detail: str
    blocking: bool


@dataclass(frozen=True)
class RecordVerdict:
    """Verdict for one Work Record.

    Status and exit_code are derived from the predicate list using the
    same rule as the overall verdict — see :func:`_status_of`.

    ``effective_rules`` lists every predicate that fired on this
    record, paired with a source label (``core`` / ``default`` / ``repo``)
    naming where the rule originated. Reviewers consume this via the
    comment formatter to answer "which rules applied, and where did
    each come from?" — SPEC §13.1's last clause.
    """

    slug: str
    status: str
    exit_code: int
    predicates: list[PredicateResult] = field(default_factory=list)
    effective_rules: list[dict[str, str]] = field(default_factory=list)


@dataclass(frozen=True)
class Verdict:
    """Aggregate verdict for a PR's checked Work Records.

    Even a single-record run wraps its record in ``records[0]`` — the
    shape is uniform so the comment formatter doesn't need a separate
    code path for the single-record case (it picks the rendering shape
    from ``len(records)``).
    """

    status: str
    """One of ``clean``, ``advisory``, ``blocking``."""

    exit_code: int
    """``0`` clean, ``1`` advisory, ``2`` blocking. Mirrors ``status``."""

    records: list[RecordVerdict] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        """JSON-serialisable view. Predicates flatten to dicts at the leaf."""
        return {
            "status": self.status,
            "exit_code": self.exit_code,
            "records": [
                {
                    "slug": r.slug,
                    "status": r.status,
                    "exit_code": r.exit_code,
                    "predicates": [asdict(p) for p in r.predicates],
                    "effective_rules": list(r.effective_rules),
                }
                for r in self.records
            ],
        }


def _status_of(predicates: list[PredicateResult]) -> tuple[str, int]:
    """Roll up a flat predicate list into (status, exit_code).

    Shared by both record-level and overall aggregation, so the same
    rule applies on both levels: any failed blocking → blocking;
    else any failed advisory → advisory; else clean.
    """
    any_blocking_failed = any(not p.passed and p.blocking for p in predicates)
    any_advisory_failed = any(not p.passed and not p.blocking for p in predicates)
    if any_blocking_failed:
        return "blocking", 2
    if any_advisory_failed:
        return "advisory", 1
    return "clean", 0


def aggregate_record(slug: str, predicates: list[PredicateResult]) -> RecordVerdict:
    """Build a :class:`RecordVerdict` from one record's predicate results."""
    status, exit_code = _status_of(predicates)
    return RecordVerdict(slug=slug, status=status, exit_code=exit_code, predicates=predicates)


def aggregate(records: list[RecordVerdict]) -> Verdict:
    """Roll up per-record verdicts into the overall :class:`Verdict`.

    The overall status applies the same rule one level up: any record
    with status ``blocking`` → overall blocking; else any record with
    status ``advisory`` → overall advisory; else overall clean.

    When ``records`` is empty (e.g. a PR that changed no Work Records),
    the overall verdict is clean — the "nothing to check" case is not
    itself a failure. The caller may surface it via a comment, but it
    is not a workflow gate.
    """
    if not records:
        return Verdict(status="clean", exit_code=0, records=[])

    if any(r.status == "blocking" for r in records):
        return Verdict(status="blocking", exit_code=2, records=records)
    if any(r.status == "advisory" for r in records):
        return Verdict(status="advisory", exit_code=1, records=records)
    return Verdict(status="clean", exit_code=0, records=records)

# ----- core/checker/redline_verdict.py -----

"""agent-redline verdict reader.

Loads the JSON document agent-redline's reporter writes (see
``core/agent-redline/tests/reporter/*/expected-verdict.json`` for the
shape) and exposes a small typed view the checker's redline predicates
consume.

Why a dedicated module:

- Redline's verdict has no JSON Schema in our copy of the source — the
  reporter goldens are the contract today. Centralising the read here
  keeps that coupling in one place; the predicates downstream don't
  need to know about defensive ``dict.get`` chains.
- Upstream redline may grow keys. The parser ignores anything it does
  not recognise and defaults missing keys to safe values. A new
  ``verdict`` string variant or a new ``*Changes`` flag won't break the
  checker — it will simply not influence the detected risk until we
  teach the parser about it.

The single classification helper here mirrors the translation table
documented in ``core/templates/checkpoints/assess-risk.md``. Keep them
in sync — the skill tells the agent how to pre-classify; this module
tells the checker how to post-classify on the final diff.
"""



# Risk vocabulary the agent-workflow checker speaks. Kept here as a
# tuple ordered low → high so callers can compare with the index. The
# string constants are deliberately not imported from
# ``core.work_record`` — that module's ``ALLOWED_RISK`` is a set, not
# ordered, and re-using its frozenset would obscure the ordering this
# module depends on.
_RISK_ORDER: tuple[str, ...] = ("Routine", "Elevated", "High")


class RedlineVerdictError(ValueError):
    """Raised when the verdict file is present but malformed.

    A missing file is not an error — :func:`load` returns ``None`` for
    that case so the caller can distinguish "absent" from "broken".
    """


@dataclass(frozen=True)
class RedlineVerdict:
    """Defensive view over redline's verdict JSON.

    Only the fields the checker reads are surfaced. The raw payload is
    kept on :attr:`raw` so downstream callers that need an upstream-
    introduced key can reach for it without waiting for a parser
    update. The structural accessors (``boundary_violations``,
    ``zones``, ``checkpoints``, the four ``*_changed`` booleans) drive
    the predicates.
    """

    boundary_violations: list[dict[str, Any]]
    """List of boundary-violation entries; each at least carries
    ``rule``, ``detail``, ``severity``, ``source``. Empty list when
    redline saw no violations on this diff."""

    zones: dict[str, list[str]]
    """``{"blue": [...], "gray": [...], "red": [...], "watch": [...]}``
    with missing keys defaulted to an empty list. Files redline could
    not classify don't appear here at all."""

    checkpoints: list[dict[str, Any]]
    """Redline's review checkpoints triggered by the diff (e.g.
    ``persistence-review``, ``api-review``). Used as a tie-breaker when
    a red-zone change has no ``*Changes.detected`` flag set."""

    api_changed: bool
    schema_changed: bool
    security_changed: bool
    runtime_config_changed: bool
    """Disambiguators for red-zone → High vs Elevated. Pulled from
    ``apiChanges.detected``, ``schemaChanges.detected``,
    ``securityChanges.detected``, ``runtimeConfigChanges.detected`` —
    each defaults to ``False`` when the key is absent."""

    modes: dict[str, Any] = field(default_factory=dict)
    """The reporter echoes the policy's ``modes`` block. Shape:
    ``{"default": "shadow"|"binding", "perCheck": {<name>: ...}}``.
    Empty dict when the reporter pre-dates the modes-echo change — in
    that case, :meth:`is_binding` defaults to ``True`` (the previously
    hardcoded behaviour) to preserve backward compatibility."""

    raw: dict[str, Any] = field(default_factory=dict)
    """The full parsed payload. Forward-compatibility escape hatch."""

    # ------------------------------------------------------------------
    # Derived properties
    # ------------------------------------------------------------------

    @property
    def has_boundary_violation(self) -> bool:
        """``True`` when redline flagged at least one boundary violation.

        Boundary violations are a separate gate in the predicate set —
        they're not a Risk-level question. The checker reads this and
        ``risk.boundary_violation_absent`` blocks on it.
        """
        return bool(self.boundary_violations)

    def detected_risk(self) -> str:
        """Translate zones + checkpoints + change flags into our Risk vocabulary.

        Translation table (in step with
        ``core/templates/checkpoints/assess-risk.md``):

        - **High** when any contract / schema / security surface
          changed (``api_changed``, ``schema_changed``,
          ``security_changed``) or when a triggered checkpoint id is
          in the well-known High set (``api-review``,
          ``persistence-review``, ``security-review``,
          ``financial-review``). These are contract-class surfaces
          where a mis-declaration matters most.
        - **Elevated** when any red or gray zone was touched, or when
          runtime configuration changed (operational surface), or when
          redline raised any unsatisfied checkpoint (the policy is
          telling us this needs human attention).
        - **Routine** otherwise (blue-only changes with no checkpoint
          and no change flag — the routine fast path).

        Boundary violations are handled by a separate predicate and do
        not affect this return value — the workflow rule is that a
        boundary violation blocks regardless of risk-level matching,
        so risk-level comparison still applies cleanly to the
        non-boundary part of the verdict.
        """
        # Step 1: High signals — contract/schema/security changes,
        # plus High-class checkpoint ids. Wins over any zone-based
        # baseline.
        if self.api_changed or self.schema_changed or self.security_changed:
            return "High"
        if self._has_high_checkpoint():
            return "High"

        # Step 2: Elevated signals — any red or gray zone touched, any
        # runtime config change, any redline checkpoint raised. We
        # don't differentiate red from gray here: that distinction
        # only affects High disambiguation (handled above).
        if self.zones.get("red") or self.zones.get("gray"):
            return "Elevated"
        if self.runtime_config_changed:
            return "Elevated"
        if self.checkpoints:
            return "Elevated"

        # Step 3: nothing flagged — blue-only or empty diff.
        return "Routine"

    def is_binding(self, check_name: str) -> bool:
        """Whether ``check_name`` is binding under the verdict's modes config.

        Mirrors the reporter's own ``_binding`` semantics so the
        agent-workflow checker arrives at the same disposition the
        reporter used when computing exit_code / recommendedAction:

        - ``perCheck.<name>`` wins when explicit (``"binding"`` or
          ``"shadow"``).
        - Otherwise falls back to ``modes.default``.
        - ``boundary_violation`` is hardcoded ``binding`` unless an
          explicit ``perCheck.boundary_violation: shadow`` flips it —
          matches the reporter (see SPEC §10.3, REDLINE.md §"Modes").

        When the verdict pre-dates the modes-echo change (``modes`` is
        empty), defaults to ``True`` — the previously hardcoded
        behaviour. Consumers that need to fail loud on an older
        reporter should check :attr:`modes` directly.
        """
        if not self.modes:
            return True
        per_check = self.modes.get("perCheck") or {}
        if check_name in per_check:
            return per_check[check_name] == "binding"
        if check_name == "boundary_violation":
            # Hardcoded default; only an explicit perCheck override flips it.
            return True
        default = self.modes.get("default") or "shadow"
        return default == "binding"

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    # The set of checkpoint ids that, when triggered by redline, push a
    # red-zone finding from Elevated to High. These names are the ones
    # redline's policy templates ship today — see
    # ``core/agent-redline/core/templates/agent-policy.yaml.template`` for
    # the canonical list. ``architecture-review`` is intentionally *not* in this set:
    # it's the default checkpoint for any red-zone change and would
    # collapse the Elevated/High distinction. The four below name
    # contract/schema/security/persistence surfaces — the same
    # categories the ``*_changed`` booleans cover.
    _HIGH_CHECKPOINT_IDS: frozenset[str] = frozenset(
        {
            "api-review",
            "persistence-review",
            "security-review",
            "financial-review",
        }
    )

    def _has_high_checkpoint(self) -> bool:
        """``True`` iff a triggered checkpoint id matches the High set."""
        for cp in self.checkpoints:
            cp_id = cp.get("id")
            if isinstance(cp_id, str) and cp_id in self._HIGH_CHECKPOINT_IDS:
                return True
        return False


